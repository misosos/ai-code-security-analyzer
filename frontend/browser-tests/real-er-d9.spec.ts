import { expect, test } from '@playwright/test';
import { writeFile } from 'node:fs/promises';
import { join } from 'node:path';

test('D9 upstream investigation displays skipped path without claiming remediation', async ({ page }) => {
  test.skip(process.env.D9_CASE !== 'upstream-ignore', 'Only the isolated ER-D9 harness selects this scenario');
  const token = process.env.BROWSER_E2E_API_TOKEN;
  const target = process.env.BROWSER_E2E_INVESTIGATION_PATH;
  if (!token || !target) throw new Error('d9_browser_context_missing');
  await page.goto('/');
  await expect(page.getByText(/API 연결됨/)).toBeVisible();
  await page.getByLabel('로컬 API 토큰').fill(token);
  await page.getByLabel('검사 대상').selectOption('synthetic-investigation');
  await expect(page.getByLabel('검사 대상').locator('option:checked')).toHaveText('Upstream EJS (격리 사본)');
  await page.getByLabel('검사 규칙 모음').selectOption('baseline');
  await page.getByText('소멸 근거 조사 선택').click();
  await page.getByLabel('소멸 근거 조사').check();
  await page.getByLabel('규칙 파일 동일성 증거 포함').check();
  const firstResponse = page.waitForResponse((response) => new URL(response.url()).pathname === '/api/v2/investigation-scans/rule-bytes');
  await page.getByRole('button', { name: '검사 실행' }).click();
  const first = await (await firstResponse).json() as { run_handle: string; scan: { scan_status: string; findings: Array<{ file_path: string }> } };
  expect(first.scan.scan_status).toBe('completed');
  expect(first.scan.findings.map((item) => item.file_path)).toEqual(['ejs.js', 'ejs.js']);
  await page.getByRole('button', { name: '현재 결과를 비교 기준으로 저장' }).click();
  await writeFile(join(target, '.semgrepignore'), 'ejs.js\n', { mode: 0o600 });
  await page.getByRole('navigation', { name: '화면 이동' }).getByRole('button', { name: /검사 시작/ }).click();
  const secondResponse = page.waitForResponse((response) => new URL(response.url()).pathname === '/api/v2/investigation-scans/rule-bytes');
  await page.getByRole('button', { name: '검사 실행' }).click();
  const second = await (await secondResponse).json() as { run_handle: string; scan: { scan_status: string; completed: boolean; findings: unknown[] } };
  expect(second.scan).toMatchObject({ scan_status: 'partial', completed: false, findings: [] });
  await page.getByRole('navigation', { name: '화면 이동' }).getByRole('button', { name: /검사 결과/ }).click();
  await page.getByText('검사 결과 비교').click();
  const panel = page.getByRole('region', { name: '소멸 근거 조사' });
  await expect(page.locator('.comparison-blocked')).toContainText('부분 검사 또는 실패한 결과는 비교할 수 없습니다.');
  const evaluationResponse = page.waitForResponse((response) => new URL(response.url()).pathname === '/api/v2/investigations/evaluate');
  await panel.getByRole('button', { name: '소멸 근거 조사 실행' }).click();
  const evaluation = await (await evaluationResponse).json() as { overall_assessment: string; findings: Array<{ path_observation: string; skip_hypothesis: string; category: string }> };
  expect(evaluation.overall_assessment).toBe('INCOMPARABLE');
  expect(evaluation.findings).toHaveLength(2);
  expect(evaluation.findings.every((item) => item.category === 'baselineOnly' && item.path_observation === 'PATH_EXPLICITLY_SKIPPED' && item.skip_hypothesis === 'SUPPORTED')).toBe(true);
  const map = page.getByRole('region', { name: 'Security Evidence Gap Map' });
  await expect(map).toBeVisible();
  await expect(map).toContainText('비교 불가');
  await expect(map).toContainText('바이트 비교 근거가 부족합니다');
  await expect(map).toContainText('소스 스냅샷을 수집하지 않았습니다');
  await expect(map).toContainText('취약점 해결 여부는 이 조사만으로 판정할 수 없습니다');
  await map.getByText(/기준 검사에서만 관찰된 Finding별 근거/).click();
  await expect(map).toContainText('ejs.js');
  await expect(map).toContainText('현재 검사에서 이 경로가 제외됐다고 보고됐습니다');
  await expect(map).toContainText('Ignore 설정 및 파일 포함 여부');
  await expect(map).not.toContainText(token);
  await expect(map).not.toContainText(target);
  await expect(map).not.toContainText(first.run_handle);
  await expect(map).not.toContainText(second.run_handle);
  await panel.getByRole('button', { name: '조사 증거 해제' }).click();
  await expect(map).toHaveCount(0);
});
