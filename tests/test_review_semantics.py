"""Independent, fixed semantic expectations for analyst review output."""

from __future__ import annotations

import json
from dataclasses import replace
from pathlib import Path

from ai_code_security_analyzer import review
from ai_code_security_analyzer.evidence_consumer import EvidenceConsumerError
from ai_code_security_analyzer.models import Finding, FindingStatus, Severity
from ai_code_security_analyzer.semgrep_adapter import ScanResult, ScanStatus
from ai_code_security_analyzer.semgrep_parser import _parse_semgrep_json_internal
from ai_code_security_analyzer.taint_evidence import build_taint_evidence


ROOT = Path(__file__).resolve().parents[1]
RULES = ROOT / "rules"
TAINT_RULE = RULES / "experimental" / "javascript-eval-taint.yml"
SANITIZER_RULE_ID = "experimental.javascript-eval-taint-with-synthetic-sanitizer"
BASELINE_RULE = RULES / "security-baseline.yml"
CANARY = "SYNTHETIC_REVIEW_CANARY_9F21"


# Fixed before invoking render_review: each row describes permitted display meaning,
# not a copy of output generated by the implementation under test.
TAINT_ORACLE = {
    "required": (
        "Semgrep이 신뢰된 taint 규칙에 따른 매치를 보고했습니다.",
        "실제 Source 위치 식별 [현재 자료에서 확인 불가]",
        "Sink 인자 위치 식별 [현재 자료에서 확인 불가]",
        "전체 데이터 흐름 경로 제공 [현재 자료에서 확인 불가]",
        "흐름이 없다는 뜻은 아닙니다.",
        "미검증 후보 (취약점·오탐 모두 미확정)",
        "실제 악용 가능성 판정은 아님",
    ),
    "forbidden": (
        "취약점이 확인됐습니다",
        "공격에 성공했습니다",
        "데이터 흐름이 존재하지 않습니다",
        "false positive입니다",
    ),
}


def _finding(
    number: int = 1,
    *,
    rule_id: str = "baseline.javascript-dynamic-eval",
    path: str = "src/synthetic.ts",
    severity: Severity = Severity.HIGH,
) -> Finding:
    return Finding(
        finding_id=f"semgrep:{number:024x}",
        rule_id=rule_id,
        title=f"Synthetic title {CANARY}",
        description=f"Synthetic private description {CANARY}",
        severity=severity,
        source_tool="semgrep",
        file_path=path,
        line_number=5,
        evidence=f"Synthetic code evidence {CANARY}",
    )


def _taint_case(tmp_path: Path, *, rule_id: str = "experimental.javascript-eval-taint"):
    target = tmp_path / "target"
    target.mkdir(parents=True)
    raw = {
        "version": "1.182.1",
        "engine_requested": "OSS",
        "results": [
            {
                "check_id": rule_id,
                "path": "src/synthetic.ts",
                "start": {"line": 5, "col": 2},
                "end": {"line": 5, "col": 8},
                "extra": {
                    "message": f"private free-form message {CANARY}",
                    "severity": "ERROR",
                    "engine_kind": "OSS",
                    "lines": f"eval('{CANARY}')",
                },
            }
        ],
        "errors": [],
    }
    parsed = _parse_semgrep_json_internal(json.dumps(raw).encode(), target)
    finding = parsed.parsed.findings[0]
    evidence = build_taint_evidence(
        parsed.document,
        parsed.result_findings,
        target,
        rules_file=TAINT_RULE,
        trusted_rules_directory=RULES,
    )
    scan = ScanResult(ScanStatus.COMPLETED, (finding,), (), 0, "1.182.1")
    return finding, evidence, scan


def _render_taint(tmp_path: Path, *, rule_id: str = "experimental.javascript-eval-taint"):
    finding, evidence, scan = _taint_case(tmp_path, rule_id=rule_id)
    return finding, evidence, scan, review.render_review(
        scan,
        evidence,
        rules_file=TAINT_RULE,
        trusted_rules_directory=RULES,
    )


def test_fixed_taint_policy_oracle_covers_supported_and_prohibited_meanings(tmp_path: Path) -> None:
    _, _, _, output = _render_taint(tmp_path)
    assert all(expected in output for expected in TAINT_ORACLE["required"])
    assert all(prohibited not in output for prohibited in TAINT_ORACLE["forbidden"])


def test_severity_verification_and_finding_count_are_distinct(tmp_path: Path) -> None:
    finding, _, _, output = _render_taint(tmp_path)
    assert finding.severity is Severity.HIGH
    assert finding.status is FindingStatus.UNVERIFIED
    assert "도구 심각도 분류별 검토 대상:" in output
    assert "Semgrep 심각도 분류: high (실제 악용 가능성 판정은 아님)" in output
    assert "검증 상태: 미검증 후보 (취약점·오탐 모두 미확정)" in output
    assert "검토 대상: 1건 (취약점 확정 수가 아님)" in output
    assert "Finding 상태: unverified" not in output


def test_pattern_and_zero_finding_oracles_do_not_overstate_results(tmp_path: Path) -> None:
    pattern = _finding()
    pattern_output = review.render_review(
        ScanResult(ScanStatus.COMPLETED, (pattern,), (), 0, "1.182.1"),
        (),
        rules_file=BASELINE_RULE,
        trusted_rules_directory=RULES,
    )
    assert "탐지 유형: 일반 패턴" in pattern_output
    assert "확인 항목: 신뢰된 taint 규칙 매치 보고" in pattern_output
    assert "Semgrep이 신뢰된 taint 규칙에 따른 매치를 보고했습니다." not in pattern_output

    zero_output = review.render_review(ScanResult(ScanStatus.COMPLETED, (), (), 0, "1.182.1"), ())
    assert "검사 상태: 정상 완료" in zero_output
    assert "검토 대상: 0건" in zero_output
    assert zero_output.count("대상 코드가 안전하다는 뜻은 아닙니다") == 1
    assert "취약점이 없습니다" not in zero_output


def test_partial_and_failed_scan_have_distinct_fixed_semantics(tmp_path: Path) -> None:
    _, evidence, completed = _taint_case(tmp_path)
    partial = replace(completed, status=ScanStatus.PARTIAL, issues=("semgrep_skipped_paths",))
    partial_output = review.render_review(
        partial, evidence, rules_file=TAINT_RULE, trusted_rules_directory=RULES
    )
    assert "검사 상태: 부분 검사" in partial_output
    assert "검사 완료: 아니요" in partial_output
    assert "전체 검사가 완료되지 않았습니다" in partial_output
    assert "Semgrep이 해당 규칙 매치를 보고했습니다." in partial_output
    assert "Semgrep이 신뢰된 taint 규칙에 따른 매치를 보고했습니다." not in partial_output
    assert "신뢰된 taint 규칙 매치 보고 [근거 부족]" in partial_output

    failed = replace(completed, status=ScanStatus.EXECUTION_FAILED)
    failed_output = review.render_review(
        failed, evidence, rules_file=TAINT_RULE, trusted_rules_directory=RULES
    )
    assert "검사 상태: 실행 실패" in failed_output
    assert "근거 검증: 실패 (scan_not_reviewable)" in failed_output
    assert "Semgrep이 신뢰된 taint 규칙에 따른 매치를 보고했습니다." not in failed_output


def test_unclassified_and_sanitizer_claims_remain_restricted(tmp_path: Path) -> None:
    _, evidence, scan, _ = _render_taint(tmp_path / "hash", rule_id=SANITIZER_RULE_ID)
    altered = (replace(evidence[0], rules_file_sha256="0" * 64),)
    output = review.render_review(
        scan, altered, rules_file=TAINT_RULE, trusted_rules_directory=RULES
    )
    assert "탐지 유형: 분류되지 않음" in output
    assert "규칙 파일의 해시가 예상값과 다릅니다." in output

    # The trusted declaration has a synthetic sanitizer, but no observed use/effect.
    _, evidence, scan = _taint_case(tmp_path / "san", rule_id=SANITIZER_RULE_ID)
    output = review.render_review(
        scan, evidence, rules_file=TAINT_RULE, trusted_rules_directory=RULES
    )
    assert "Sanitizer 매치 관찰 [현재 자료에서 확인 불가]" in output
    assert "Sanitizer 효과 검증 [이 분석에서 지원하지 않는 판단]" in output
    assert "정제 함수의 실제 보안 효과는 검증되지 않았습니다." in output


def test_consumer_failure_never_becomes_a_supported_review_claim(tmp_path: Path, monkeypatch) -> None:
    finding, evidence, scan = _taint_case(tmp_path)

    def reject(*_args, **_kwargs):
        raise EvidenceConsumerError("synthetic_consumer_rejection")

    monkeypatch.setattr(review, "consume_evidence_summary", reject)
    output = review.render_review(
        scan, evidence, rules_file=TAINT_RULE, trusted_rules_directory=RULES
    )
    assert "근거 검증: 실패 (review_evidence_validation_failed)" in output
    assert "확인된 사실: 표시할 수 없습니다." in output
    assert "Semgrep이 신뢰된 taint 규칙에 따른 매치를 보고했습니다." not in output


def test_multiple_findings_and_output_omission_preserve_totals(tmp_path: Path, monkeypatch) -> None:
    findings = tuple(_finding(index) for index in range(1, 4))
    scan = ScanResult(ScanStatus.COMPLETED, findings, (), 0, "1.182.1")
    monkeypatch.setattr(review, "MAX_REVIEW_FINDINGS", 1)
    output = review.render_review(scan, ())
    assert "검토 대상: 3건" in output
    assert "검토 대상 #1" in output
    assert "검토 대상 #2" not in output
    assert "출력 제한으로 표시하지 않은 검토 대상: 2건" in output
    assert "생략된 항목의 개별 검증 상태는 확인할 수 없으며 안전하다고 판단할 수 없습니다" in output


def test_special_paths_and_semgrep_canary_do_not_reach_review_output(tmp_path: Path) -> None:
    target = tmp_path / "target"
    target.mkdir()
    raw = {
        "version": "1.182.1",
        "engine_requested": "OSS",
        "results": [
            {
                "check_id": "baseline.javascript-dynamic-eval",
                "path": "src/escape\u001b[31m\nname.ts",
                "start": {"line": 5, "col": 2},
                "end": {"line": 5, "col": 8},
                "extra": {
                    "message": f"private tool text {CANARY}",
                    "severity": "ERROR",
                    "engine_kind": "OSS",
                    "lines": f"eval('{CANARY}')",
                },
            }
        ],
        "errors": [],
    }
    parsed = _parse_semgrep_json_internal(json.dumps(raw).encode(), target)
    finding = parsed.parsed.findings[0]
    output = review.render_review(
        ScanResult(ScanStatus.COMPLETED, (finding,), (), 0, "1.182.1"), ()
    )
    assert "src/escape\\u001b[31m\\nname.ts" in output
    assert "\u001b" not in output
    assert CANARY not in output


def test_byte_limit_fallback_states_exact_omission_counts(monkeypatch) -> None:
    findings = (_finding(), _finding(2))
    scan = ScanResult(ScanStatus.COMPLETED, findings, (), 0, "1.182.1")
    monkeypatch.setattr(review, "MAX_REVIEW_OUTPUT_BYTES", 512)
    output = review.render_review(scan, ())
    assert "검토 대상: 2건" in output
    assert "표시된 상세: 0건" in output
    assert "생략된 상세: 2건 (전체 보고서 바이트 제한)" in output
    assert "개별 검증 상태는 이 화면에서 확인할 수 없습니다" in output
    assert len(output.encode("utf-8")) <= 512
